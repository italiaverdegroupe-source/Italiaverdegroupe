// Turns db/seed/blocks.<locale>.tsv into src/lib/content-translations.ts.
//
//   node scripts/compile-block-translations.mjs
//
// The translations were written months ago and never reached a visitor. They
// lived only in those TSVs and in a seeding script nothing ran — not
// package.json, not the Dockerfile, not railway.json — so content_blocks was
// empty in production and every page fell back to the English compiled into
// content.ts. Two thirds of the words on /ar were Latin script.
//
// Seeding on deploy would fix it once and then rot the moment somebody edited
// a block in the console. Compiling them in fixes it permanently: the English
// fallback already ships in the bundle, so the other two travel the same way,
// and the database — when it has a row — still wins over both.
import { readFileSync, writeFileSync } from 'node:fs';

const LOCALES = ['ar', 'it'];
const out = {};
for (const loc of LOCALES) {
  const rows = readFileSync(`db/seed/blocks.${loc}.tsv`, 'utf8')
    .split('\n').map((l) => l.trim()).filter(Boolean)
    .map((l) => { const i = l.indexOf('\t'); return [l.slice(0, i), l.slice(i + 1)]; });
  out[loc] = Object.fromEntries(rows);
  console.log(loc, rows.length, 'blocks');
}

const body = `/**
 * The Arabic and Italian copy for every editable block.
 *
 * GENERATED by scripts/compile-block-translations.mjs from db/seed/blocks.*.tsv.
 * Edit the TSVs and re-run; do not edit this file by hand.
 *
 * It exists because the translations were written, committed, and then never
 * loaded: the seeding script was in no build step, content_blocks was empty in
 * production, and getBlocks() fell through to the English compiled into
 * content.ts. Arabic and Italian visitors read an English homepage.
 *
 * Compiled rather than seeded on deploy, for the same reason the English
 * fallback is compiled: the production image is built with no database, so
 * anything that depends on a row existing is a page that can ship empty. The
 * database still wins where it has a value — this is the floor, not the
 * ceiling.
 */
import type { Locale } from '@/lib/i18n';

export const BLOCK_TRANSLATIONS: Partial<Record<Locale, Record<string, string>>> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync('src/lib/content-translations.ts', body);
console.log('wrote src/lib/content-translations.ts');
